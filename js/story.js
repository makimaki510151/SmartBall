function buildCosts(n, target) {
  const raw = [];
  for (let i = 0; i < n; i += 1) {
    const t = n === 1 ? 0 : i / (n - 1);
    raw.push(2.15 + (t ** 1.72) * 96);
  }
  const scale = target / raw.reduce((a, b) => a + b, 0);
  const costs = raw.map((v) => Math.max(2, Math.round(v * scale)));
  for (let i = 1; i < n; i += 1) {
    if (costs[i] < costs[i - 1]) costs[i] = costs[i - 1];
  }
  let diff = target - costs.reduce((a, b) => a + b, 0);
  let guard = 0;
  let i = n - 1;
  while (diff !== 0 && guard < n * 10) {
    guard += 1;
    if (diff > 0) {
      costs[i] += 1;
      diff -= 1;
    } else {
      const floor = i === 0 ? 2 : costs[i - 1];
      if (costs[i] > floor) {
        costs[i] -= 1;
        diff += 1;
      }
    }
    i -= 1;
    if (i < 0) i = n - 1;
  }
  return costs;
}

export const COSTS = buildCosts(LINES.length, 100000);
export const BALL_TOTAL = COSTS.reduce((a, b) => a + b, 0);

export function costAt(index) {
  return COSTS[index] || 0;
}

const prefix = new Array(COSTS.length + 1);
prefix[0] = 0;
for (let i = 0; i < COSTS.length; i += 1) prefix[i + 1] = prefix[i] + COSTS[i];

export function spentBefore(count) {
  const n = Math.max(0, Math.min(COSTS.length, count | 0));
  return prefix[n];
}

